let cached: Lang | undefined;

export function reportLang(): Lang {
  if (!cached) {
    const tab = extendedTabs().find(t => t.format === 'insights');
    try {
      cached = tab ? (JSON.parse(tab.content).language === 'en' ? 'en' : 'ru') : 'ru';
    } catch {
      cached = 'ru';
    }
  }
  return cached;
}

export function texts(): typeof ru {
  return reportLang() === 'en' ? en : ru;
}
